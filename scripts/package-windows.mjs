// Build a per-user installer from the Windows release output. Only listed application
// files enter the manifest, even when a developer packages their existing portable copy.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliDecompressSync } from 'node:zlib';
import { execFileSync } from 'node:child_process';
const root = fileURLToPath(new URL('../', import.meta.url));
const stage = path.resolve(process.argv[2] || path.join(root, 'artifacts/demo'));
const nsis = process.argv[3] || 'makensis';
const version = fs.readFileSync(path.join(root, 'src/ZmxyDemo/ZmxyDemo.csproj'), 'utf8').match(/<Version>(\d+\.\d+\.\d+)<\/Version>/)[1];
const output = path.join(root, 'artifacts/windows', 'ZmxyStudio-' + version + '-Windows-x64-Setup.exe');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'zmxy-installer-'));
const flag = process.platform === 'win32' ? '/' : '-';

// This is the same Chromium license document served by CEF's built-in about:credits.
// CEF 84 stores it in resource 16290 of its v5 DataPack, with an 8-byte Brotli header.
function extractCredits() {
  const pak = fs.readFileSync(path.join(stage, 'cef.pak'));
  if (pak.readUInt32LE(0) !== 5) throw new Error('Unexpected CEF DataPack version');
  for (let i = 0; i < pak.readUInt16LE(8); i++) {
    const offset = 12 + i * 6;
    if (pak.readUInt16LE(offset) !== 16290) continue;
    const item = pak.subarray(pak.readUInt32LE(offset + 2), pak.readUInt32LE(offset + 8));
    if (item.readUInt16BE(0) !== 0x1e9b) break;
    const html = brotliDecompressSync(item.subarray(8));
    if (!html.includes('Generated by licenses.py')) break;
    const file = path.join(scratch, 'Chromium-credits.html');
    fs.writeFileSync(file, html);
    return file;
  }
  throw new Error('Could not locate Chromium notices in cef.pak');
}

const mainFiles = [
  'ZmxyDemo.exe', 'ZmxyDemo.exe.config', 'ZmxySubprocess.exe', 'ZmxySubprocess.exe.config',
  'zmxy-speed.dll', 'app.ico', 'test-page.html', 'CefSharp.dll', 'CefSharp.Core.dll',
  'CefSharp.WinForms.dll', 'CefSharp.BrowserSubprocess.Core.dll', 'CefSharp.BrowserSubprocess.exe',
  'Newtonsoft.Json.dll', 'libcef.dll', 'chrome_elf.dll', 'd3dcompiler_47.dll',
  'libEGL.dll', 'libGLESv2.dll', 'icudtl.dat', 'v8_context_snapshot.bin', 'snapshot_blob.bin',
  'cef.pak', 'cef_100_percent.pak', 'cef_200_percent.pak', 'cef_extensions.pak', 'devtools_resources.pak'
];
try {
  const files = mainFiles.map(name => [path.join(stage, name), name]);
  for (const name of fs.readdirSync(path.join(stage, 'locales')).filter(name => /^[a-zA-Z0-9-]+\.pak$/.test(name))) {
    files.push([path.join(stage, 'locales', name), 'locales/' + name]);
  }
  if (!files.some(([, name]) => name === 'locales/zh-CN.pak')) throw new Error('Missing CEF Chinese locale');
  for (const name of ['libEGL.dll','libGLESv2.dll']) files.push([path.join(stage, 'swiftshader', name), 'swiftshader/' + name]);
  for (const name of ['CEF.txt','CefSharp.txt','MinHook.txt','Newtonsoft.Json.md','README.md']) {
    files.push([path.join(root, 'THIRD-PARTY', name), 'THIRD-PARTY/' + name]);
  }
  files.push([extractCredits(), 'THIRD-PARTY/Chromium-credits.html']);
  const install = [], uninstall = [];
  const dirs = new Set();
  let currentDirectory;
  for (const [source, relative] of files) {
    if (!fs.statSync(source).isFile()) throw new Error('Missing file: ' + source);
    const directory = path.posix.dirname(relative);
    const dest = '$INSTDIR\\app' + (directory === '.' ? '' : '\\' + directory);
    dirs.add(dest);
    if (dest !== currentDirectory) {
      install.push('SetOutPath "' + dest + '"');
      currentDirectory = dest;
    }
    install.push('File "' + source.split('$').join('$$') + '"');
    uninstall.push('Delete "' + dest + '\\' + path.basename(relative) + '"');
  }
  uninstall.push('Delete "$INSTDIR\\app\\installed.flag"');
  for (const dir of [...dirs].reverse()) uninstall.push('RMDir "' + dir + '"');
  fs.writeFileSync(path.join(scratch, 'install.nsh'), '\uFEFF' + install.join('\n'));
  fs.writeFileSync(path.join(scratch, 'uninstall.nsh'), '\uFEFF' + uninstall.join('\n'));
  fs.mkdirSync(path.dirname(output), { recursive: true });
  execFileSync(nsis, [flag+'INPUTCHARSET','UTF8',flag+'V2',flag+'DVERSION='+version,
    flag+'DOUTPUT='+output,flag+'DMANIFEST='+scratch,path.join(root, 'packaging/windows/studio.nsi')], {stdio:'inherit'});
  console.log(output);
} finally { fs.rmSync(scratch, { recursive: true, force: true }); }
